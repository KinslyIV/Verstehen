import { test, expect } from '../fixtures';
test.use({ script: 'verify/scripts/session.json' });
test('session-rename-delete', async ({ page }) => {
	await page.goto('/');
	await page.getByRole('textbox', { name: 'What do you want to learn?' }).fill('Derivatives');
	await page.getByRole('button', { name: 'Send', exact: true }).click();
	await expect(page).toHaveURL(/\/session\/[^/]+$/);
	await expect(page.getByRole('button', { name: "AGENT'S THINKING", exact: true })).toBeVisible();
	await expect(page.getByRole('button', { name: 'Send', exact: true })).toBeVisible();
	await page.getByRole('button', { name: 'Derivatives', exact: true }).click();
	await page.getByRole('textbox', { name: 'Session title' }).fill('Slope');
	await page.getByRole('textbox', { name: 'Session title' }).press('Enter');
	await page.getByRole('link', { name: /Slope/ }).click({ button: 'right' });
	await page.getByRole('menuitem', { name: 'Rename' }).click();
	await page.getByRole('textbox', { name: 'Session title' }).fill('Rates');
	await page.getByRole('textbox', { name: 'Session title' }).press('Enter');
	await expect(page.getByRole('button', { name: 'Rates', exact: true })).toBeVisible();
	await page.getByRole('link', { name: /Rates/ }).click({ button: 'right' });
	await page.getByRole('menuitem', { name: 'Delete' }).click();
	await expect(page.getByRole('dialog')).toContainText('Rates');
	await page.getByRole('button', { name: 'Cancel', exact: true }).click();
	await page.getByRole('link', { name: /Rates/ }).click({ button: 'right' });
	await page.getByRole('menuitem', { name: 'Delete' }).click();
	await page.getByRole('button', { name: 'Delete', exact: true }).click();
	await expect(page.getByRole('heading', { name: 'New session' })).toBeVisible();
	await expect(page.getByText('No sessions yet')).toBeVisible();
});
